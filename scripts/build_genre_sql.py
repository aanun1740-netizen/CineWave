"""Generate the review-only backfill; never connects to a database."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data/genre-backfill.json').read_text())
def literal(value):
    return "'"+str(value).replace("'","''")+"'"
values=[]
for row in data['updates']:
    genres='ARRAY['+','.join(map(literal,row['genre_names']))+']::text[]'
    values.append('  ('+','.join([str(int(row['id'])),literal(row['expected_title']),literal(row['expected_release_date'])+'::date',genres,literal(row['imdb_id'])])+')')
sql='''-- REVIEW ONLY. Generated by python3 scripts/build_genre_sql.py.
-- Do not run against Supabase until the owner approves database modifications.
-- Source records, aliases and unresolved films: data/genre-backfill.json.
-- Default is ROLLBACK. After approval, review the returned rows and change
-- the final ROLLBACK to COMMIT only when ready to persist this transaction.
-- No schema, catalog connection, artwork or AI changes are made here.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'movies'
      AND column_name = 'genre_names' AND udt_name = '_text'
  ) THEN
    RAISE EXCEPTION 'Expected public.movies.genre_names to be text[]; inspect schema before proceeding';
  END IF;
END $$;
CREATE TEMP TABLE cinewave_genre_candidates (
  movie_id bigint PRIMARY KEY,
  expected_title text NOT NULL,
  expected_release_date date NOT NULL,
  genre_names text[] NOT NULL CHECK (cardinality(genre_names) > 0),
  imdb_id text NOT NULL
) ON COMMIT DROP;
INSERT INTO cinewave_genre_candidates VALUES
'''+',\n'.join(values)+''';

-- Preview identity mismatches and existing genres before the guarded update.
SELECT c.movie_id, c.expected_title, c.imdb_id, m.genre_names AS current_genres,
       c.genre_names AS proposed_genres,
       CASE WHEN m.id IS NULL THEN 'skip: row missing'
            WHEN m.title_en IS DISTINCT FROM c.expected_title
              OR m.release_date IS DISTINCT FROM c.expected_release_date
              THEN 'skip: identity changed'
            WHEN EXISTS (SELECT 1 FROM unnest(m.genre_names) AS g(value)
                         WHERE NULLIF(btrim(g.value), '') IS NOT NULL)
              THEN 'skip: genres already present'
            ELSE 'eligible' END AS status
FROM cinewave_genre_candidates AS c
LEFT JOIN public.movies AS m ON m.id = c.movie_id
ORDER BY c.movie_id;

UPDATE public.movies AS m
SET genre_names = c.genre_names
FROM cinewave_genre_candidates AS c
WHERE m.id = c.movie_id
  AND m.title_en = c.expected_title
  AND m.release_date = c.expected_release_date
  AND NOT EXISTS (
    SELECT 1 FROM unnest(m.genre_names) AS g(value)
    WHERE NULLIF(btrim(g.value), '') IS NOT NULL
  )
RETURNING m.id, m.title_en, m.genre_names;

-- Safe default: no persistent database changes. Approval is required to commit.
ROLLBACK;
'''
(root/'sql/backfill_missing_genres.sql').write_text(sql)
