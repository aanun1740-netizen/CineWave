"""Prepare approval-gated seed SQL. Does not connect to Supabase."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data/playback-films.json').read_text())
def q(value):return 'NULL' if value is None else "'"+str(value).replace("'","''")+"'"
def boolean(value):return 'true' if value is True else 'false'
values=[]
for film in data['films']:
 genres='ARRAY['+','.join(q(g) for g in film['genre_names'])+']::text[]'
 values.append('  ('+','.join([q(film['title_en']),q(film['release_date'])+'::date',q(film['watch_url']),q(film['attribution']),q(film['identity_source']),q(film['license_source']),q(film['license_terms_source']),genres,boolean(film['verified']),boolean(film['commercial_reuse_verified'])])+')')
sql='''-- REVIEW ONLY. No production execution without explicit owner approval.
-- Generated by scripts/build_playback_sql.py from data/playback-films.json.
-- BLOCKED: candidates are NOT verified. This script currently raises an
-- exception before any movie insertion. Do not bypass the evidence gate.
-- After verification and approval, keep is_published=false for initial review.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
CREATE TEMP TABLE cinewave_playback_candidates (
 title_en text NOT NULL,
 release_date date,
 watch_url text,
 attribution text,
 identity_source text,
 license_source text,
 license_terms_source text,
 genre_names text[] NOT NULL,
 identity_and_video_verified boolean NOT NULL,
 commercial_reuse_verified boolean NOT NULL
) ON COMMIT DROP;
INSERT INTO cinewave_playback_candidates VALUES
'''+',\n'.join(values)+''';
DO $$
BEGIN
 IF EXISTS (
  SELECT 1 FROM cinewave_playback_candidates
  WHERE NOT identity_and_video_verified OR NOT commercial_reuse_verified
     OR release_date IS NULL OR watch_url IS NULL OR watch_url !~ '^https://'
     OR NULLIF(btrim(attribution), '') IS NULL
     OR NULLIF(btrim(identity_source), '') IS NULL
     OR NULLIF(btrim(license_source), '') IS NULL
     OR NULLIF(btrim(license_terms_source), '') IS NULL
 ) THEN
  RAISE EXCEPTION 'Film verification incomplete: verify identity, exact media URL, license, commercial reuse and attribution before inserting any movies';
 END IF;
END $$;
-- Serialize reviewed seed runs. Lock timeout prevents waiting indefinitely.
LOCK TABLE public.movies IN SHARE ROW EXCLUSIVE MODE;
SELECT c.title_en, c.release_date, c.watch_url, c.attribution,
       c.identity_source, c.license_source, c.license_terms_source,
       CASE WHEN EXISTS (SELECT 1 FROM public.movies m
         WHERE lower(btrim(m.title_en)) = lower(btrim(c.title_en))
           AND extract(year FROM m.release_date) = extract(year FROM c.release_date))
         THEN 'skip: title/year exists' ELSE 'insert unpublished' END AS action
FROM cinewave_playback_candidates c;
-- Rely on the existing database ID default; never assign existing IDs or
-- change a sequence. If the default collides, the whole transaction fails.
INSERT INTO public.movies (title_en, overview_en, release_date, genre_names, watch_url, is_published)
SELECT c.title_en,
       c.attribution || E'\\nOriginal: ' || c.identity_source || E'\\nLicense: ' || c.license_source || E'\\nTerms: ' || c.license_terms_source,
       c.release_date, c.genre_names, c.watch_url, false
FROM cinewave_playback_candidates c
WHERE NOT EXISTS (
 SELECT 1 FROM public.movies m
 WHERE lower(btrim(m.title_en)) = lower(btrim(c.title_en))
   AND extract(year FROM m.release_date) = extract(year FROM c.release_date)
)
RETURNING id, title_en, release_date, watch_url, is_published;
-- Safe default. Owner approval is required to change this to COMMIT.
ROLLBACK;
'''
(root/'sql/seed_playback_movies.sql').write_text(sql)
